#!/usr/bin/env python3
"""
tools/png2h.py  —  Converts a PNG file to a C header with raw BGRA pixel data.
Images are resized to TARGET_W x TARGET_H to keep the binary small enough for
create-eboot to produce a valid SELF (large ELFs cause silent failure).

Usage:
    python3 tools/png2h.py <input.png> <output.h> <varname>
"""

import sys
from pathlib import Path
from PIL import Image

# 320×240 → 3 images × 320×240×4 bytes = ~369 KB binary (vs 3.6MB at 640×480)
TARGET_W = 320
TARGET_H = 240

def main():
    if len(sys.argv) != 4:
        print(f"Usage: {sys.argv[0]} <input.png> <output.h> <varname>")
        sys.exit(1)

    src  = Path(sys.argv[1])
    dst  = Path(sys.argv[2])
    name = sys.argv[3]

    img = Image.open(src).convert("RGBA").resize((TARGET_W, TARGET_H), Image.LANCZOS)
    W, H = img.size
    pixels = list(img.getdata())

    dst.parent.mkdir(parents=True, exist_ok=True)

    with open(dst, "w") as f:
        f.write(f"// Auto-generated by tools/png2h.py from {src.name} (resized to {W}x{H})\n")
        f.write(f"// Format: BGRA uint32 (little-endian: B=bits[7:0], R=bits[23:16])\n")
        f.write(f"#pragma once\n")
        f.write(f"#include <stdint.h>\n\n")
        f.write(f"#define {name.upper()}_W {W}\n")
        f.write(f"#define {name.upper()}_H {H}\n\n")
        f.write(f"static const uint32_t {name}[{W * H}] = {{\n")

        per_row = 8
        for i, (r, g, b, a) in enumerate(pixels):
            # Pack as BGRA uint32 (little-endian — B in low byte)
            val = (a << 24) | (r << 16) | (g << 8) | b
            if i % per_row == 0:
                f.write("    ")
            f.write(f"0x{val:08X}U")
            if i < len(pixels) - 1:
                f.write(", ")
            if (i + 1) % per_row == 0:
                f.write("\n")
        if len(pixels) % per_row != 0:
            f.write("\n")
        f.write("};\n")

    raw_kb = W * H * 4 / 1024
    print(f"  ✓ {src.name}  →  {dst}  ({W}x{H}, {raw_kb:.0f} KB binary)")

if __name__ == "__main__":
    main()
